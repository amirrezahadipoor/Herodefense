def corpus() -> list[str]:
    """Every case the shaper has to get right, in an order that puts the mechanics first."""
    cases: list[str] = []

    # 1. Each letter on its own: the isolated form, and the proof that a letter with no medial form (ا د ر ز
    #    ژ و) never invents one.
    cases.extend(letter for letter in PERSIAN_LETTERS)

    # 2. Each letter between two dual-joining carriers: the medial form.
    cases.extend(f"ب{letter}ب" for letter in PERSIAN_LETTERS)

    # 3. Each letter leading and trailing: the initial and final forms.
    cases.extend(f"{letter}ب" for letter in PERSIAN_LETTERS)
    cases.extend(f"ب{letter}" for letter in PERSIAN_LETTERS)

    # 4. The lam-alef ligature, which is mandatory rather than decorative, in both of its forms and with each
    #    of the alefs that can carry a hamza.
    cases.extend(["لا", "لأ", "لإ", "لآ", "سلام", "بلا", "الله", "الا", "کلاه"])

    # 5. The zero-width non-joiner, which Persian needs the way English needs a space: می‌رود is one word and
    #    two joins that must not happen.
    cases.extend(["می‌رود", "خانه‌ها", "بازی‌ها", "سیب‌زمینی", "به‌هم", "‌", "ب‌ب"])

    # 6. The zero-width joiner, and the tatweel, which stretches a join without adding a letter.
    cases.extend(["ب‍ب", "بـب", "ـ", "بـ"])

    # 7. Harakat, which the reference deletes: a vowel mark is not a letter and must not become a join.
    cases.extend(["بَ", "بِ", "بُ", "بً", "بٍ", "بٌ", "بّ", "بْ", "مُحمَّد"])

    # 8. Numbers and Latin inside a Persian sentence. This is where a naive shaper breaks: the digits stay in
    #    their own order while the words around them reverse.
    cases.extend([
        "موج ۱۴۰",
        "۲۰۰ موج یا سی",
        "سطح ۵",
        "۵۰٪",
        "HP ۵۰",
        "Wave 140",
        "موج 140",
        "۰۱۲۳۴۵۶۷۸۹",
        "۱۲۳ بازی ۴۵۶",
        "Tier 3 | Peak 175 | 42 HW",
    ])

    # 9. Punctuation, which belongs to the run it sits in: the Persian comma and question mark are not the
    #    ASCII ones, and a full stop between two Persian words reverses with them.
    cases.extend(["بازی جدید؟", "بله، ادامه", "نه!", "سلام.", "«درخت»", "(موج)", "الف؛ب"])

    # 10. The empty and the already-shaped: shaping must be safe to call on anything the table holds.
    cases.extend(["", " ", "  ", "\u200f", "\u200e"])

    # 11. Everything the game says.
    cases.extend(UI_STRINGS)

    seen: set[str] = set()
    unique = [case for case in cases if not (case in seen or seen.add(case))]
    return unique


def shape(text: str) -> str:
    """The reference answer: contextual forms, then visual order."""
    import arabic_reshaper
    from bidi.algorithm import get_display

    return get_display(arabic_reshaper.reshape(text))


def versions() -> dict[str, str]:
    from importlib import metadata

    return {name: metadata.version(name) for name in REFERENCE_VERSIONS}


def render() -> str:
    found = versions()
    for name, want in REFERENCE_VERSIONS.items():
        got = found.get(name)
        if got != want:
            raise SystemExit(
                f"{name} is {got}, the golden vectors were generated with {want}. "
                "Re-run without --check only if the difference has been looked at."
            )

    lines = [HEADER.format(
        reshaper=found["arabic-reshaper"],
        bidi=found["python-bidi"],
        # The interpreter is named by minor version and by the Unicode data it carries, because those are the
        # two things that could change an answer: python-bidi asks unicodedata for each character's bidi class
        # and its mirrored pair, and that table is a property of the CPython minor, not of its patch level. A
        # patch release cannot drift this file, so recording one only ever made `--check` fail on a machine
        # that was equally right. CI pins this minor with actions/setup-python for the same reason.
        python=".".join(str(part) for part in sys.version_info[:2]),
        unicode=unicodedata.unidata_version,
    ).rstrip("\n")]
    for case in corpus():
        visual = shape(case)
        hexed = " ".join(f"{ord(character):04X}" for character in visual)
        one_line = case.replace("\n", "\\n").replace("\t", "\\t")
        lines.append(f"{one_line}\t{hexed}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail instead of writing")
    parser.add_argument("--count", action="store_true", help="print the corpus size and stop")
    arguments = parser.parse_args()

    if arguments.count:
        print(f"{len(corpus())} vectors")
        return 0

    produced = render()
    if arguments.check:
        if not GOLDEN.is_file():
            print(f"MISSING {GOLDEN}")
            return 2
        committed = GOLDEN.read_text(encoding="utf-8")
        if committed != produced:
            print(f"DRIFT {GOLDEN}: the reference no longer produces the committed vectors")
            print(f"  committed lines: {len(committed.splitlines())}")
            print(f"  generated lines: {len(produced.splitlines())}")
            for index, (was, now) in enumerate(
                zip(committed.splitlines(), produced.splitlines())
            ):
                if was != now:
                    print(f"  first difference at line {index + 1}")
                    print(f"    committed: {was[:160]}")
                    print(f"    generated: {now[:160]}")
                    break
            return 2
        print(f"OK {GOLDEN} matches arabic_reshaper + python-bidi on {len(corpus())} vectors")
        return 0

    GOLDEN.parent.mkdir(parents=True, exist_ok=True)
    GOLDEN.write_text(produced, encoding="utf-8")
    print(f"wrote {GOLDEN} ({len(corpus())} vectors)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
