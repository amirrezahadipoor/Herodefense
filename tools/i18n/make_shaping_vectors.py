#!/usr/bin/env python3
"""Write the shaping vectors the Persian shaper is held to (roadmap R7.3).

The game draws text with a bitmap font, and a bitmap font has no shaper: libGDX rasterises the codepoints it
is given, in the order it is given them. Persian needs both halves of that solved -- every letter takes one of
four forms depending on its neighbours, and the run is written right to left while the digits and Latin words
inside it stay left to right.

`core/src/main/java/.../render/PersianShaper.java` does that in the game, in pure Java. This tool is how the
repository knows it is right: it asks two libraries this repository did not write -- `arabic_reshaper` for the
contextual forms and `python-bidi` for the reordering -- to shape the same corpus, and writes their answers
into `golden/shaping-vectors.txt`. `PersianShaperTest` then asserts the Java shaper reproduces every vector,
codepoint for codepoint.

That is the same shape of evidence as the ETC2 encoder being held to Google's reference blocks: the
implementation is ours, the expectation is not.

Usage:
    python3 tools/i18n/make_shaping_vectors.py           # write the golden file
    python3 tools/i18n/make_shaping_vectors.py --check   # fail if the golden file is not what the reference says

The reference libraries are pinned by version below, because the golden file is a statement about *their*
output: if a library changes what it produces, `--check` fails and the change is a decision, not a surprise.
"""

from __future__ import annotations

import argparse
import pathlib
import sys
import unicodedata

HERE = pathlib.Path(__file__).resolve().parent
GOLDEN = HERE / "golden" / "shaping-vectors.txt"

# The versions the committed golden file was generated with. `--check` refuses to compare against anything
# else, so an upgraded library cannot quietly redefine what "correctly shaped" means.
REFERENCE_VERSIONS = {
    "arabic-reshaper": "3.0.1",
    "python-bidi": "0.6.11",
}

HEADER = """# Persian shaping vectors, generated by tools/i18n/make_shaping_vectors.py -- do not edit by hand.
#
# Each line is: <logical text> TAB <visual codepoints, hex, space separated>.
# "Logical" is what the string table says; "visual" is what a left-to-right bitmap font must be handed for the
# eye to read it as Persian. Produced by arabic_reshaper {reshaper} + python-bidi {bidi} on CPython {python}
# with Unicode {unicode}.
#
# The Java shaper (render/PersianShaper.java) has to reproduce every line. PersianShaperTest fails on the first
# one it does not, printing both sides as codepoints.
"""

